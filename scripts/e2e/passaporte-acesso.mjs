// Destructive only to its own fake account, guarded to Next dev + local store.
import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { criarStoreLocal } from '../../app/lib/selo/storeLocal.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.PASSAPORTE_TEST_URL || 'http://127.0.0.1:3018';
if (!['127.0.0.1', 'localhost'].includes(new URL(origin).hostname)) throw new Error('Teste de acesso exige servidor local.');
const store = criarStoreLocal();
const nome = 'Teste Acesso Gratuito';
const telefone = '11900006789';
const senha = 'Minha senha local de teste 2026';
const nova = 'Outra senha local de teste 2026';
if (store.porWhatsapp(telefone)) throw new Error('Conta de teste já existe; não sobrescrever.');
const output = '/private/tmp/pistaviva-acesso-mobile';
await mkdir(output, { recursive: true });
const checks = [];
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, acceptDownloads: true });
  assert.equal((await context.request.get(origin + '/selo/passaporte/previa/jornada')).status(), 200, 'Recusa build de produção ou Supabase real.');
  await context.route('**/*', r => new URL(r.request().url()).origin === origin ? r.continue() : r.abort());
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin + '/selo/passaporte#criar-passaporte', { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.locator('#pc-nome:not([disabled])').waitFor();
  await page.locator('#pc-nome').fill(nome);
  await page.locator('#pc-wa').fill(telefone);
  await page.locator('#pc-cidade').fill('Itajubá');
  await page.locator('#pc-uf').selectOption('MG');
  await page.locator('#pc-senha').fill(senha);
  await page.locator('#pc-confirmacao').fill(senha);
  await page.getByLabel('Aceito o uso dos meus dados', { exact: false }).check();
  await page.getByRole('button', { name: 'Criar meu passaporte', exact: true }).click();
  await page.locator('.acesso-segredo').waitFor({ timeout: 60000 });
  const recuperacao = await page.locator('.acesso-segredo').innerText();
  assert.match(recuperacao, /^([A-F0-9]{4}-){7}[A-F0-9]{4}$/);
  assert.equal(await page.evaluate(() => localStorage.getItem('selo:perfil')), null);
  const dl = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Baixar código', exact: true }).click();
  const downloaded = await dl;
  await downloaded.saveAs(output + '/codigo-conta-ficticia.txt');
  const texto = await readFile(output + '/codigo-conta-ficticia.txt', 'utf8');
  assert.ok(texto.includes(recuperacao)); assert.ok(!texto.includes(senha));
  await page.screenshot({ path: output + '/codigo-390.png' });
  await page.getByRole('button', { name: 'Guardei o código. Abrir passaporte', exact: true }).click();
  await page.waitForURL(/\/selo\/m\/[a-f0-9]{12}/);
  const antigo = new URL(page.url()).pathname.split('/').at(-1);
  const id = store.motoPorCodigo(antigo).id;
  assert.equal(store.porWhatsapp(telefone)?.codigo, antigo);
  checks.push('Cadastro persistido com senha; código aparece uma vez e pode ser baixado, sem mensagem externa');
  await page.evaluate(() => localStorage.clear());
  await page.goto(origin + '/selo/meu-numero', { waitUntil: 'domcontentloaded' });
  await page.locator('#acesso-whatsapp').fill(telefone);
  await page.locator('#acesso-senha').fill(nova);
  await page.getByRole('button', { name: 'Entrar no meu passaporte', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Não foi possível confirmar' }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/selo/meu-numero');
  await page.locator('#acesso-senha').fill(senha);
  await page.getByRole('button', { name: 'Entrar no meu passaporte', exact: true }).click();
  await page.waitForURL(`**/selo/m/${antigo}*`);
  assert.equal(await page.evaluate(() => /codigoRecuperacao|senha/i.test(localStorage.getItem('selo:perfil'))), false);
  checks.push('Entrar de outro aparelho com telefone e senha; senha errada não devolve acesso');
  await page.goto(origin + '/selo/meu-numero', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Esqueci a senha', exact: true }).click();
  await page.locator('#acesso-iniciais').fill('Tes');
  await page.locator('#acesso-finais').fill('6789');
  await page.locator('#acesso-cidade').fill('itajuba');
  await page.locator('#acesso-uf').selectOption('MG');
  await page.screenshot({ path: output + '/localizar-390.png' });
  await page.getByRole('button', { name: 'Continuar recuperação', exact: true }).click();
  await page.locator('#acesso-senha').fill(nova);
  await page.locator('#acesso-confirmacao').fill(nova);
  await page.getByRole('button', { name: 'Trocar senha e recuperar', exact: true }).click();
  await page.locator('#acesso-codigoRecuperacao-erro').waitFor();
  assert.ok(store.motoPorCodigo(antigo));
  await page.locator('#acesso-codigoRecuperacao').fill('A'.repeat(32));
  await page.getByRole('button', { name: 'Trocar senha e recuperar', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Não foi possível confirmar' }).waitFor();
  await page.locator('#acesso-codigoRecuperacao').fill(recuperacao);
  await page.screenshot({ path: output + '/recuperar-390.png' });
  await page.getByRole('button', { name: 'Trocar senha e recuperar', exact: true }).click();
  await page.locator('.acesso-segredo').waitFor({ timeout: 60000 });
  assert.notEqual(await page.locator('.acesso-segredo').innerText(), recuperacao);
  assert.equal(await page.evaluate(() => localStorage.getItem('selo:perfil')), null);
  assert.equal((await context.request.get(origin + `/selo/m/${antigo}`)).status(), 404);
  assert.equal(store.motoPorCodigo(antigo), null);
  await page.getByRole('button', { name: 'Guardei o novo código. Entrar', exact: true }).click();
  await page.locator('#acesso-whatsapp').fill(telefone);
  await page.locator('#acesso-senha').fill(senha);
  await page.getByRole('button', { name: 'Entrar no meu passaporte', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Não foi possível confirmar' }).waitFor();
  await page.locator('#acesso-senha').fill(nova);
  await page.getByRole('button', { name: 'Entrar no meu passaporte', exact: true }).click();
  await page.waitForURL(/\/selo\/m\/[a-f0-9]{12}/);
  const atual = new URL(page.url()).pathname.split('/').at(-1);
  assert.notEqual(atual, antigo); assert.equal(store.motoPorCodigo(atual).id, id);
  checks.push('Recuperação exige código salvo, troca senha e link, mantém mesma conta e pede login novo');
  await page.goto(origin + '/selo/meu-numero', { waitUntil: 'domcontentloaded' });
  for (const width of [320, 390, 430, 844]) {
    await page.setViewportSize({ width, height: width === 844 ? 390 : 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#acesso-whatsapp').fill(telefone);
  await page.locator('#acesso-senha').fill(senha);
  for (let n = 0; n < 2; n++) {
    await page.getByRole('button', { name: 'Entrar no meu passaporte', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.acesso-form button[type="submit"]').disabled);
  }
  await page.getByRole('alert').filter({ hasText: 'Muitas tentativas' }).waitFor();
  assert.deepEqual(errors, []);
  checks.push('Limite por conta bloqueia tentativas repetidas; quatro larguras sem transbordamento');
  await writeFile(output + '/report.json', JSON.stringify({ origin, ok: true, checks }, null, 2));
  console.log(JSON.stringify({ ok: true, checks }, null, 2));
} finally {
  await browser.close();
  const pessoa = store.ler().motociclistas.find((m) => m.whatsapp === telefone && m.nome === nome);
  if (pessoa) store.excluirMotociclista(pessoa.id);
}

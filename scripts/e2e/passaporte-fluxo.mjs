// Local only. Usage: PLAYWRIGHT_MODULE=/path/to/playwright/index.mjs node scripts/e2e/passaporte-fluxo.mjs
import assert from 'node:assert/strict';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { criarStoreLocal } from '../../app/lib/selo/storeLocal.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.PASSAPORTE_TEST_URL || 'http://127.0.0.1:3000';
if (!['127.0.0.1', 'localhost'].includes(new URL(origin).hostname)) throw new Error('Este teste só pode gravar em servidor local.');
const output = '/private/tmp/pistaviva-fluxo-implementado';
await mkdir(output, { recursive: true });
const store = criarStoreLocal();
const phone = '11900008673';
const name = 'Teste Fluxo Mobile';
if (store.porWhatsapp(phone)) throw new Error('Número de teste já ocupado. Escolha outro antes de executar.');
const checks = [];
const ok = check => { checks.push(check); console.log(check); };
const browser = await chromium.launch({ channel: 'chrome', headless: true });
let page;
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'pt-BR' });
  const localOnly = await context.request.get(`${origin}/selo/passaporte/previa/jornada`, { timeout: 60000 });
  assert.equal(localOnly.status(), 200, 'Exige Next dev com store local; não usar next start nem SELO_STORE=supabase.');
  await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  await context.addInitScript(() => {
    window.testGpsCalls = 0;
    navigator.geolocation.getCurrentPosition = (_ok, fail) => { window.testGpsCalls++; fail({ code: 1 }); };
  });
  page = await context.newPage();
  await page.goto(`${origin}/selo/passaporte`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.evaluate(() => document.fonts.ready);
  const nav = page.getByRole('navigation', { name: 'Navegação do passaporte', exact: true });
  assert.equal(await nav.locator('a,button').count(), 4);
  await page.locator('#amostra-passaporte .sl-phone').waitFor();
  assert.equal(await page.locator('.leaflet-container').count(), 0);
  await page.screenshot({ path: `${output}/entrada-390.png` });
  await page.getByRole('link', { name: 'Criar meu passaporte grátis', exact: true }).click();
  await page.waitForTimeout(350);
  assert.equal(await page.locator('#pc-nome').evaluate(e => { const r = e.getBoundingClientRect(); return r.top >= 56 && r.bottom <= innerHeight - 64; }), true);
  assert.equal(await page.locator('#pp-criar-titulo').evaluate(e => getComputedStyle(e).fontSize), '32px');
  await page.screenshot({ path: `${output}/cadastro-390.png` });
  ok('Amostra preenchida na entrada, cadastro direto, quatro destinos e mapa adiado');
  await page.getByRole('button', { name: 'Criar meu passaporte', exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.id === 'pc-nome');
  assert.equal(await page.locator('#pc-nome').getAttribute('aria-describedby'), 'pc-nome-erro');
  await page.locator('#pc-nome').fill(name);
  await page.locator('#pc-wa').fill(phone);
  await page.locator('#pc-cidade').fill('Itajubá');
  await page.locator('#pc-uf').selectOption('MG');
  await page.locator('#pc-senha').fill('Senha de teste fluxo mobile 2026');
  await page.locator('#pc-confirmacao').fill('Senha de teste fluxo mobile 2026');
  await page.getByLabel('Aceito o uso dos meus dados para o passaporte', { exact: false }).check();
  await page.getByRole('button', { name: 'Criar meu passaporte', exact: true }).click();
  await page.getByRole('button', { name: 'Guardei o código. Abrir passaporte', exact: true }).click();
  await page.waitForFunction(() => /^\/selo\/m\/[a-f0-9]{12}$/.test(location.pathname), { timeout: 60000 });
  const code = new URL(page.url()).pathname.split('/').at(-1);
  assert.equal(store.porWhatsapp(phone)?.codigo, code, 'Cadastro deve existir exclusivamente no store local.');
  const stamp = page.getByRole('button', { name: 'Carimbar esta cidade', exact: true });
  await stamp.waitFor();
  assert.equal(await page.evaluate(() => window.testGpsCalls), 0);
  assert.equal(await stamp.evaluate(e => { const r = e.getBoundingClientRect(); return r.top >= 56 && r.bottom <= innerHeight - 64; }), true);
  await page.screenshot({ path: `${output}/carimbar-390.png` });
  ok('Cadastro local conclui no carimbo; GPS só após toque');
  await stamp.click();
  await page.getByRole('alert').filter({ hasText: 'Localização bloqueada' }).waitFor();
  await page.evaluate(() => {
    navigator.geolocation.getCurrentPosition = done => done({ coords: { latitude: -22.4258, longitude: -45.4528, accuracy: 12 } });
  });
  await stamp.click();
  await page.locator('.carimbo-feito').waitFor({ timeout: 60000 });
  assert.equal(await page.getByRole('checkbox', { name: /Mostrar no mapa/ }).isChecked(), false);
  await page.locator('.carimbo-feito').screenshot({ path: `${output}/sucesso-privado.png` });
  ok('GPS negado tem recuperação; carimbo real local e foto privada por padrão');
  assert.equal((await context.request.get(`${origin}/api/selo/passaporte?codigo=${code}`)).status(), 401);
  const collection = await context.request.get(`${origin}/api/selo/passaporte`, { headers: { Authorization: `Bearer ${code}` } });
  assert.equal(collection.status(), 200);
  assert.match(collection.headers()['cache-control'], /no-store/);
  const data = await collection.json();
  assert.equal(data.carimbos.length, 1);
  assert.equal('codigo' in data, false);
  ok('API privada recusa credencial na query; header autenticado carrega coleção sem cache');
  await page.getByRole('button', { name: 'Mais', exact: true }).click();
  await page.getByRole('link', { name: /Personalizar Foto, garupa/ }).click();
  await page.locator('#sl-foto').waitFor({ state: 'attached' });
  await page.locator('#sl-foto').setInputFiles(resolve('public/selo/passaporte/home-passaporte.webp'));
  await page.waitForFunction(() => Boolean(JSON.parse(localStorage.getItem('selo:foto') || 'null')?.codigo));
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('selo:foto')).codigo), code);
  await page.goto(`${origin}/selo/m/${code}`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  let confirmou = false;
  page.once('dialog', dialog => { confirmou = true; return dialog.accept(); });
  await page.getByRole('button', { name: 'Esquecer este celular', exact: true }).click();
  assert.equal(confirmou, true, 'Esquecimento exige confirmação explícita.');
  await page.waitForFunction(() => location.pathname === '/selo/passaporte', null, { timeout: 60000 });
  assert.equal(await page.evaluate(() => localStorage.getItem('selo:foto')), null);
  assert.equal(await page.evaluate(() => localStorage.getItem('selo:perfil')), null);
  ok('Personalização explícita vincula foto ao dono; esquecer remove foto e perfil');
  await page.goto(`${origin}/selo`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForFunction(() => { const submit = document.querySelector('#selo-cadastro button[type="submit"]'); return submit && !submit.disabled; });
  await page.locator('#selo-nome').fill(name);
  await page.locator('#selo-whatsapp').fill(phone);
  await page.locator('#selo-uf').selectOption('MG');
  await page.locator('#selo-cidade').fill('Itajubá');
  await page.locator('input[name=passou_por]').first().check();
  await page.locator('#selo-aceite_lgpd').check();
  await page.getByRole('button', { name: 'Receber meu selo', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'abra seu passaporte salvo' }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/selo');
  ok('Formulário antigo não entrega acesso a telefone já cadastrado sem credencial');
  await page.evaluate(({ codigo, nome }) => localStorage.setItem('selo:perfil', JSON.stringify({ codigo, nome })), { codigo: code, nome: name });
  await page.reload({ waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForFunction(() => { const submit = document.querySelector('#selo-cadastro button[type="submit"]'); return submit && !submit.disabled; });
  await page.getByRole('button', { name: 'Receber meu selo', exact: true }).click();
  await page.waitForFunction(expected => location.pathname === `/selo/m/${expected}`, code);
  ok('Dono com credencial válida continua registrando estação no formulário antigo');
  await page.evaluate(() => localStorage.clear());
  await page.goto(`${origin}/selo/meu-numero`, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.getByRole('button', { name: 'Esqueci a senha', exact: true }).click();
  assert.equal(await page.getByRole('link', { name: 'Falar com a equipe', exact: true }).getAttribute('href'), '/contato');
  ok('Recuperação orienta equipe quando código salvo foi perdido; dados não liberam acesso sozinhos');
  for (const width of [320, 430, 844]) {
    await page.setViewportSize({ width, height: width === 844 ? 390 : 844 });
    await page.goto(`${origin}/selo/passaporte`, { waitUntil: 'domcontentloaded', timeout: 60000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `${output}/entrada-${width}.png` });
  }
  ok('Sem overflow em 320, 430 e paisagem 844 × 390');
  await writeFile(`${output}/report.json`, JSON.stringify({ origin, checks, ok: true }, null, 2));
  await Promise.all(['falha.png', 'falha.txt'].map(file => rm(`${output}/${file}`, { force: true })));
} catch (error) {
  if (page) {
    await page.screenshot({ path: `${output}/falha.png` }).catch(() => {});
    await writeFile(`${output}/falha.txt`, await page.locator('body').innerText()).catch(() => {});
  }
  throw error;
} finally {
  await browser.close();
  const account = store.porWhatsapp(phone);
  if (account?.nome === name) store.excluirMotociclista(account.id);
}
